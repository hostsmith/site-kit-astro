// site-core, "Decap config for core sites": the whole config.yml, generated
// from a core site's schema export (site-kit-core-split design D78).
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { readFile, rm } from "node:fs/promises";
import { join } from "node:path";
import { after, describe, it } from "node:test";
import { parse } from "yaml";
import { generateConfig } from "../packages/site-kit-astro/scripts/core/decap-core.mjs";
import { assertBuilt, BASICS, buildCoreSite, buildSite, CORE_SITE, copySite, coreSiteCopy, REPO, siteKit } from "./helpers.mjs";

const LOCALES_SITE = join(REPO, "tests", "fixtures", "core-site-locales");
const read = (dir, file) => JSON.parse(readFileSync(join(dir, file), "utf8"));
const configOf = (dir) => generateConfig(read(dir, ".hostsmith/schema.json"), read(dir, "hostsmith.json"));
const text = configOf(CORE_SITE);
const config = parse(text);
const collection = (cfg, name) => cfg.collections.find((c) => c.name === name);
const fieldOf = (fields, name) => fields.find((f) => f.name === name);

function* walk(value) {
  if (Array.isArray(value)) for (const item of value) yield* walk(item);
  else if (value && typeof value === "object") {
    yield value;
    for (const item of Object.values(value)) yield* walk(item);
  }
}

// Fields of every collection and file, with where they are.
function* allFields(cfg) {
  const inner = function* (fields, where) {
    for (const field of fields ?? []) {
      yield [field, `${where}.${field.name}`];
      yield* inner(field.fields, `${where}.${field.name}`);
      if (field.field) yield* inner([field.field], `${where}.${field.name}`);
    }
  };
  for (const c of cfg.collections) {
    yield* inner(c.fields, c.name);
    for (const file of c.files ?? []) yield* inner(file.fields, `${c.name}/${file.name}`);
  }
}

describe("a core site's Decap config", () => {
  it("names the command and the export, and says not to edit it", () => {
    assert.match(text, /^# Decap CMS config, generated by `site-kit decap-config` from \.hostsmith\/schema\.json\.\n# Don't edit this file/);
  });

  it("uses the github backend with cms.repo, and the media folders", () => {
    assert.deepEqual(config.backend, { name: "github", repo: "example-agency/bakery-site", branch: "main" });
    assert.equal(config.media_folder, "public/assets");
    assert.equal(config.public_folder, "/assets");
  });

  it("has news as a folder collection with a body, and copy as a files collection", () => {
    const news = collection(config, "news");
    assert.equal(news.folder, "src/content/news");
    assert.equal(news.extension, "md");
    assert.equal(news.format, "frontmatter");
    assert.equal(news.create, true);
    assert.deepEqual(fieldOf(news.fields, "body"), { name: "body", label: "Body", widget: "markdown" });
    const copy = collection(config, "copy");
    assert.deepEqual(copy.files.map((file) => [file.name, file.file]), [
      ["about", "src/content/copy/about.yml"],
      ["home", "src/content/copy/home.yml"],
      ["site", "src/content/copy/site.yml"],
    ]);
  });

  it("gives each field its widget, label, hint and required flag", () => {
    const news = collection(config, "news").fields;
    assert.deepEqual(fieldOf(news, "date"), { name: "date", label: "Date", widget: "datetime", format: "YYYY-MM-DD", date_format: "YYYY-MM-DD", time_format: false });
    assert.deepEqual(fieldOf(news, "summary"), { name: "summary", label: "Summary", widget: "string", hint: "One sentence for the news list." });
    assert.deepEqual(fieldOf(news, "category"), { name: "category", label: "Category", widget: "select", options: ["Bakery", "Events"] });
    assert.deepEqual(fieldOf(news, "image"), { name: "image", label: "Image", widget: "image", required: false });
    assert.deepEqual(fieldOf(news, "featured"), { name: "featured", label: "Featured", widget: "boolean", required: false });
    const home = collection(config, "copy").files.find((file) => file.name === "home").fields;
    assert.equal(fieldOf(home, "hero").widget, "object");
    assert.equal(fieldOf(fieldOf(home, "hero").fields, "linkLabel").label, "Link label");
    const bakes = fieldOf(collection(config, "copy").files.find((file) => file.name === "about").fields, "bakes");
    assert.deepEqual(fieldOf(bakes.fields, "items"), { name: "items", label: "Items", widget: "list", field: { name: "item", label: "Items", widget: "string" } });
  });

  it("has no i18n in a site in one language", () => {
    assert.ok(!text.includes("i18n"));
  });

  it("uses no Sveltia-only options and no dropped features", () => {
    for (const option of ["omit_empty_optional_fields", "omit_default_locale_from_file_path", "slugify_filename", "local_backend", "duplicate_if_empty", "initial_locales"]) {
      assert.ok(!text.includes(option), `config.yml uses ${option}`);
    }
    assert.doesNotMatch(text, /git-gateway|netlify|bitbucket|azure|remark/i);
    for (const node of walk(config)) {
      if (node.widget === "image" || node.widget === "file") assert.ok(!("multiple" in node), `${node.name} uses "multiple"`);
      if (Array.isArray(node.types)) assert.ok(node.types.every((type) => type.fields?.length), `${node.name} has a type without fields`);
    }
  });

  it("lets the CMS save a field left empty", () => {
    const blocking = [];
    const check = (fields, where, inOptionalObject) => {
      for (const field of fields ?? []) {
        const required = field.required !== false;
        if (inOptionalObject && required) blocking.push(`${where}.${field.name}: required in an optional object`);
        if (field.widget === "select" && "default" in field && required) blocking.push(`${where}.${field.name}: a select with a default`);
        check(field.fields, `${where}.${field.name}`, field.widget === "object" && !required);
      }
    };
    for (const c of config.collections) {
      check(c.fields, c.name, false);
      for (const file of c.files ?? []) check(file.fields, `${c.name}/${file.name}`, false);
    }
    assert.deepEqual(blocking, []);
  });
});

describe("a translated core site's Decap config", () => {
  const translated = parse(configOf(LOCALES_SITE));

  it("has the site's locales at the top, as kit sites do", () => {
    assert.deepEqual(translated.i18n, { structure: "multiple_files", locales: ["en", "de"], default_locale: "en" });
  });

  it("gives news its locale folders and copy one file per page with every locale", () => {
    assert.deepEqual(collection(translated, "news").i18n, { structure: "multiple_folders" });
    const copy = collection(translated, "copy");
    assert.deepEqual(copy.i18n, { structure: "single_file" });
    assert.ok(copy.files.every((file) => file.i18n === true));
  });

  it("translates every field and nested field", () => {
    for (const [field, where] of allFields(translated)) assert.equal(field.i18n, true, `${where} isn't translated`);
  });
});

describe("generating a core site's Decap config", () => {
  const schema = read(CORE_SITE, ".hostsmith/schema.json");
  const manifest = read(CORE_SITE, "hostsmith.json");
  const withNews = (fields, extra = {}) => ({ ...schema, collections: { news: { ...schema.collections.news, ...extra, fields } } });

  it("fails without cms.repo, naming it in hostsmith.json", () => {
    const { cms, ...rest } = manifest;
    assert.throws(() => generateConfig(schema, rest), /hostsmith\.json needs cms\.repo/);
  });

  it("fails on a field with no widget, naming the collection and the field", () => {
    const fields = { type: "object", properties: { title: { type: "string", "x-widget": "string" }, target: { anyOf: [{ type: "string" }, { type: "boolean" }] } } };
    assert.throws(() => generateConfig(withNews(fields), manifest), /Collection "news": field "target" has no widget the CMS can show/);
  });

  it("names an entry by its first required string without a title", () => {
    const fields = { type: "object", properties: { name: { type: "string", "x-widget": "string" } }, required: ["name"] };
    assert.equal(collection(parse(generateConfig(withNews(fields), manifest)), "news").identifier_field, "name");
  });

  it("fails on locale folders with subfolders, saying to put the locale in file names", () => {
    const locales = { default: "en", codes: ["en", "de"], structure: "multiple_folders" };
    const translatedManifest = { ...manifest, content: { ...manifest.content, locales: { default: "en", codes: ["en", "de"] } } };
    assert.throws(
      () => generateConfig(withNews(schema.collections.news.fields, { pattern: "**/*.md", locales }), translatedManifest),
      /Collection "news" has folders below its locale folders.*put the locale in the file names/,
    );
  });

  it("lists nested entries with the locale in their file names", () => {
    const news = collection(parse(generateConfig(withNews(schema.collections.news.fields, { pattern: "**/*.md" }), manifest)), "news");
    assert.deepEqual(news.nested, { depth: 10, subfolders: false });
  });
});

describe("site-kit decap-config in both kinds of site", () => {
  const copies = [];
  after(() => Promise.all(copies.map((dir) => rm(dir, { recursive: true, force: true }))));

  it("assembles a kit site's config and generates a core site's", async () => {
    const kit = await copySite(BASICS);
    const core = await coreSiteCopy();
    copies.push(kit, core);
    for (const dir of [kit, core]) {
      const result = await siteKit(dir, ["decap-config"]);
      assert.equal(result.code, 0, result.output);
    }
    assert.match(await readFile(join(kit, "public/admin/config.yml"), "utf8"), /^# Decap CMS config, assembled by `npm run decap-config` from the kit's part/);
    assert.equal(await readFile(join(core, "public/admin/config.yml"), "utf8"), text);
  });

  it("fails in a core site without cms.repo, naming it", async () => {
    const core = await coreSiteCopy({ edit: { "hostsmith.json": (json) => json.replace(/,\n  "cms": \{[^}]*\}/, "") } });
    copies.push(core);
    const result = await siteKit(core, ["decap-config"]);
    assert.notEqual(result.code, 0);
    assert.match(result.output, /hostsmith\.json needs cms\.repo/);
  });
});

describe("a core site's committed Decap config", () => {
  const copies = [];
  after(() => Promise.all(copies.map((dir) => rm(dir, { recursive: true, force: true }))));
  const STALE = /public\/admin\/config\.yml doesn't match \.hostsmith\/schema\.json\. .*site-kit decap-config/;

  it("passes --check and the build in both fixtures", async () => {
    for (const fixture of ["core-site", "core-site-locales"]) {
      const dir = await coreSiteCopy({ fixture });
      copies.push(dir);
      const check = await siteKit(dir, ["decap-config", "--check"]);
      assert.equal(check.code, 0, check.output);
      assertBuilt(await buildSite(dir));
    }
  });

  it("fails --check and the build once the export changes without decap-config, naming it", async () => {
    const dir = await coreSiteCopy({ edit: { "src/content.config.ts": (ts) => ts.replace("featured: z.boolean().optional(),", "featured: z.boolean().optional(),\n    author: z.string().optional(),") } });
    copies.push(dir);
    const schema = await siteKit(dir, ["schema"]);
    assert.equal(schema.code, 0, schema.output);
    const check = await siteKit(dir, ["decap-config", "--check"]);
    assert.notEqual(check.code, 0);
    assert.match(check.output, STALE);
    const build = await buildSite(dir);
    assert.equal(build.ok, false);
    assert.match(build.output, STALE);
  });

  it("only warns in the build without the config", async () => {
    const build = await buildCoreSite({ remove: ["public/admin"] });
    await build.cleanup();
    assertBuilt(build);
    assert.match(build.output, /public\/admin\/config\.yml is missing\. Run npm run decap-config/);
  });
});
