// A core site's whole Decap config, public/admin/config.yml, generated from
// its schema export (site-kit-core-split design D78):
//
//   npm run decap-config             # in a core site, writes config.yml
//   npm run decap-config -- --check  # fails when config.yml is stale
//
// Decap CMS and Sveltia CMS both open it, with no Hostsmith service, so a
// site keeps its CMS when it leaves. It uses only the Decap-compatible subset
// of the kit's content model, with the i18n settings kit sites use
// (site-kit-locales D55), and none of Sveltia's own. In a kit site, the
// command assembles the kit's part and the site's part instead
// (scripts/decap-config.mjs).
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { stringify } from "yaml";
import { manifestLocales } from "./locales.mjs";
import { contentSource, externalSite, MANIFEST, readManifest } from "./manifest.mjs";
import { EXPORT_COMMAND, EXPORT_FILE } from "./schema-export.mjs";

export const CORE_CONFIG = "public/admin/config.yml";
export const DECAP_COMMAND = "site-kit decap-config";

const HEADER = [
  `# Decap CMS config, generated by \`${DECAP_COMMAND}\` from ${EXPORT_FILE}.`,
  "# Don't edit this file: change the site's collections, then run",
  `# \`npx ${EXPORT_COMMAND}\` and \`npm run decap-config\`.`,
  "#",
  "# Decap CMS and Sveltia CMS both read it. The build removes /admin, so it is",
  "# never deployed.",
  "",
].join("\n");

const FORMATS = { markdown: "frontmatter", yaml: "yml", json: "json" };
// How deep Decap lists the subfolders of a collection with nested entries.
const NESTED_DEPTH = 10;
const LINK_HINT = "An internal link starts with /, such as /about.";

// The config's text, from the parsed schema export and manifest.
export function generateConfig(schema, manifest) {
  const repo = manifest.cms?.repo;
  if (typeof repo !== "string" || !/^[\w.-]+\/[\w.-]+$/.test(repo)) {
    throw new Error(`${MANIFEST} needs cms.repo: the GitHub repository the CMS saves to, as "OWNER/REPOSITORY".`);
  }
  const locales = manifestLocales(manifest, "core");
  const config = {
    backend: { name: "github", repo, branch: "main" },
    media_folder: schema.media.dir,
    public_folder: schema.media.publicPath,
    ...(locales && { i18n: { structure: "multiple_files", locales: locales.codes, default_locale: locales.default } }),
    // A collection whose entries come from elsewhere has nothing to edit here (D86).
    collections: Object.entries(schema.collections)
      .filter(([, collection]) => collection.editable !== false)
      .map(([name, collection]) => (collection.type === "files" ? filesCollection(name, collection) : folderCollection(name, collection))),
  };
  return HEADER + stringify(config, { lineWidth: 0 });
}

function folderCollection(name, collection) {
  const i18n = collection.locales !== null;
  const nested = collection.pattern.startsWith("**/");
  if (nested && collection.locales?.structure === "multiple_folders") {
    throw new Error(
      `Collection "${name}" has folders below its locale folders. Decap's nested collections read a locale folder as a folder of the default locale, so put the locale in the file names, such as ${collection.path}/a.de.md.`,
    );
  }
  const fields = decapFields(name, collection.fields, { i18n, optional: false, path: [] });
  if (collection.format === "markdown") fields.push({ name: "body", label: "Body", widget: "markdown", ...(i18n && { i18n: true }) });
  return {
    name,
    label: labelOf(name),
    folder: collection.path,
    ...(i18n && { i18n: collection.locales.structure === "multiple_files" ? true : { structure: collection.locales.structure } }),
    ...(nested && { nested: { depth: NESTED_DEPTH, subfolders: false } }),
    extension: collection.pattern.slice(collection.pattern.lastIndexOf(".") + 1),
    format: FORMATS[collection.format],
    create: true,
    ...identifier(name, collection.fields),
    fields,
  };
}

// Decap names an entry by its `title` field, or by the field this names.
function identifier(name, fields) {
  if (fields.properties?.title) return {};
  const required = new Set(fields.required ?? []);
  const field = Object.entries(fields.properties ?? {}).find(([key, schema]) => required.has(key) && schema["x-widget"] === "string");
  if (!field) throw new Error(`Collection "${name}" has no "title" field and no required string field, which the CMS needs to name its entries.`);
  return { identifier_field: field[0] };
}

function filesCollection(name, collection) {
  const i18n = collection.locales !== null;
  return {
    name,
    label: labelOf(name),
    ...(i18n && { i18n: { structure: "single_file" } }),
    files: Object.entries(collection.files).map(([id, file]) => ({
      name: id,
      label: labelOf(id),
      file: file.path,
      ...(i18n && { i18n: true }),
      fields: decapFields(`${name}/${id}`, file.fields, { i18n, optional: false, path: [] }),
    })),
  };
}

// An object's fields. Decap won't save an optional object whose fields are
// required, so inside an optional object every field is optional.
function decapFields(where, object, { i18n, optional, path }) {
  const required = new Set(object.required ?? []);
  return Object.entries(object.properties ?? {}).map(([name, schema]) => decapField(where, name, schema, { required: required.has(name) && !optional, i18n, path: [...path, name] }));
}

function decapField(where, name, schema, { required, i18n, path }) {
  const field = { name, label: schema.title ?? labelOf(name), ...widgetOf(where, schema, { required, i18n, path }) };
  if (schema.description) field.hint = schema.description;
  else if (schema["x-widget"] === "link") field.hint = LINK_HINT;
  if (!required) field.required = false;
  if (i18n) field.i18n = true;
  return field;
}

// The Decap widget for a field's `x-widget` (D78's table).
function widgetOf(where, schema, { required, i18n, path }) {
  switch (schema["x-widget"]) {
    case "string":
    case "link":
      return { widget: "string" };
    case "text":
    case "markdown":
    case "image":
    case "boolean":
      return { widget: schema["x-widget"] };
    case "datetime":
      return { widget: "datetime", format: "YYYY-MM-DD", date_format: "YYYY-MM-DD", time_format: false };
    case "select":
      return { widget: "select", options: schema.enum };
    case "number":
      return { widget: "number", value_type: schema.type === "integer" ? "int" : "float" };
    case "object":
      return { widget: "object", fields: decapFields(where, schema, { i18n, optional: !required, path }) };
    case "list": {
      const items = schema.items ?? {};
      if (items["x-widget"] === "object") return { widget: "list", fields: decapFields(where, items, { i18n, optional: false, path }) };
      const { name: _, label: __, ...item } = decapField(where, "item", items, { required: true, i18n, path: [...path, "item"] });
      return { widget: "list", field: { name: "item", label: labelOf(path.at(-1)), ...item } };
    }
    default:
      throw new Error(
        `Collection "${where.split("/")[0]}": field "${path.join(".")}" has no widget the CMS can show, such as a union of types. Give it one with .meta({ "x-widget": "string" }), or change its type.`,
      );
  }
}

// "heroTitle" and "hero-title" are "Hero title".
function labelOf(name) {
  const words = name.replace(/([a-z0-9])([A-Z])/g, "$1 $2").replace(/[-_]+/g, " ").toLowerCase();
  return words.charAt(0).toUpperCase() + words.slice(1);
}

// The committed config against a fresh generation from the committed export:
// "missing", "stale", or undefined when it matches.
export function configState(root, text) {
  const file = join(root, CORE_CONFIG);
  if (!existsSync(file)) return "missing";
  return readFileSync(file, "utf8") === text ? undefined : "stale";
}

export const CONFIG_MESSAGES = {
  missing: `${CORE_CONFIG} is missing. Run npm run decap-config, or npx ${DECAP_COMMAND}, and commit the file, so Decap and Sveltia can edit the site.`,
  stale: `${CORE_CONFIG} doesn't match ${EXPORT_FILE}. Don't edit it: run npm run decap-config, or npx ${DECAP_COMMAND}, and commit the file.`,
};

// The config a core site's committed export gives.
export function configOf(root) {
  const manifest = readManifest(root);
  if (!manifest) throw new Error(`Missing ${MANIFEST}. ${DECAP_COMMAND} reads cms.repo from it.`);
  const file = join(root, EXPORT_FILE);
  if (!existsSync(file)) throw new Error(`Missing ${EXPORT_FILE}. Run npx ${EXPORT_COMMAND} first: ${DECAP_COMMAND} generates the CMS config from it.`);
  return generateConfig(JSON.parse(readFileSync(file, "utf8")), manifest);
}

function main(args) {
  const unknown = args.filter((arg) => arg !== "--check");
  if (unknown.length > 0) throw new Error(`Usage: site-kit decap-config [--check]. Unknown: ${unknown.join(" ")}.`);
  const manifest = readManifest(".");
  if (manifest && contentSource(manifest, "core") === "external") {
    console.log(externalSite(`${DECAP_COMMAND} writes no Decap config`));
    return;
  }
  const text = configOf(".");
  if (args.includes("--check")) {
    const state = configState(".", text);
    if (state) throw new Error(CONFIG_MESSAGES[state]);
    console.log(`${CORE_CONFIG} is up to date.`);
    return;
  }
  mkdirSync(dirname(CORE_CONFIG), { recursive: true });
  writeFileSync(CORE_CONFIG, text);
  console.log(`Wrote ${CORE_CONFIG} from ${EXPORT_FILE}.`);
}

// `site-kit decap-config [--check]` in a core site (bin/site-kit.mjs).
export function cli(args) {
  try {
    main(args);
  } catch (error) {
    console.error(error.message);
    process.exit(1);
  }
}
